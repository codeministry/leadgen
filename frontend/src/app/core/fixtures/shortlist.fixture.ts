import { ShortlistEntry } from '@core/model/shortlist-entry';

function entry(
  id: string,
  title: string,
  description: string,
  location: string | null,
  portal: string,
  agency: string | null,
  publishedOn: string,
  tags: readonly string[],
  score: number | null,
  reasons: readonly [string, string, number][],
  extra: Partial<{
    rateEur: number | null;
    remotePercent: number | null;
    startsOn: string | null;
    duration: string | null;
    incomplete: boolean;
    alsoOn: readonly [string, string | null][];
  }> = {},
): ShortlistEntry {
  const url = `https://example.invalid/projekt/${id}`;
  return {
    offer: {
      id,
      externalId: `ext-${id}`,
      title,
      description,
      url,
      location,
      portal,
      agency,
      publishedOn,
      tags,
      rateEur: extra.rateEur ?? null,
      remotePercent: extra.remotePercent ?? null,
      startsOn: extra.startsOn ?? null,
      duration: extra.duration ?? null,
      language: 'de',
    },
    score: {
      value: score,
      hardPass: true,
      reasons: reasons.map(([factor, label, points]) => ({ factor, label, points })),
      model: score === null ? null : 'configured-model',
      rulesetVersion: '1',
    },
    flags: {
      incomplete: extra.incomplete ?? false,
      remoteUnknown: (extra.remotePercent ?? null) === null,
    },
    sources: [
      { portal, agency, url },
      ...(extra.alsoOn ?? []).map(([p, a]) => ({ portal: p, agency: a, url })),
    ],
  };
}

